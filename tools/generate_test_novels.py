def create_test_novel(file_manager: ProjectManager, novel_name: str, novel_data: dict):
    file_manager.init_novel(novel_name)
    
    global_dir = file_manager.get_global_settings_path(novel_name)
    
    file_manager.save_content(global_dir / "bios.json", novel_data["bios"])
    file_manager.save_content(global_dir / "world.md", novel_data["world"])
    file_manager.save_content(global_dir / "relation_graph.json", novel_data["relations"])
    
    for chapter_data in novel_data["chapters"]:
        chapter_num = chapter_data["chapter_num"]
        chapter_path = file_manager.init_chapter(novel_name, chapter_num)
        
        file_manager.save_content(chapter_path / "outline.md", chapter_data["outline"])
        file_manager.save_content(chapter_path / "content.md", chapter_data["content"])
        
        meta = {
            "chapter_num": chapter_num,
            "title": chapter_data.get("title", ""),
            "status": "completed",
            "word_count": len(chapter_data["content"]),
            "created_at": datetime.now().isoformat(),
            "updated_at": datetime.now().isoformat()
        }
        file_manager.save_content(chapter_path / "meta.json", meta)


